roti = 100
print("Stok roti berjumlah :",roti)

roti += 50
print("Roti setelah produksi :",roti)

roti *= 3
print("Roti produksi lagi karena banyak pesanan sebesar :",roti)

roti -= 120
print("roti tersisa setelah dikirim:",roti)

roti //=4
print("Roti bagi menjadi 4 etalase,masing masing berjumlah:",roti)

roti += 10
print("roti pada setiap etalase bertambah menjadi :",roti)